CREATE TABLE IF NOT EXISTS public.people (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  hire_date text NOT NULL,
  end_date text,
  department text NOT NULL,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  type text NOT NULL,
  date text NOT NULL,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.attendance (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id bigint NOT NULL REFERENCES public.people(id) ON DELETE CASCADE,
  event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  status text NOT NULL,
  created_at timestamptz DEFAULT now(),
  CONSTRAINT attendance_person_event_unique UNIQUE (person_id, event_id)
);

CREATE TABLE IF NOT EXISTS public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE public.people ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendance ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

GRANT ALL ON public.people, public.events, public.attendance, public.users TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

CREATE OR REPLACE FUNCTION public.advance_id_sequences()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  PERFORM pg_catalog.setval(
    pg_catalog.pg_get_serial_sequence('public.people', 'id')::regclass,
    COALESCE((SELECT MAX(id) FROM public.people), 1),
    EXISTS (SELECT 1 FROM public.people)
  );
  PERFORM pg_catalog.setval(
    pg_catalog.pg_get_serial_sequence('public.events', 'id')::regclass,
    COALESCE((SELECT MAX(id) FROM public.events), 1),
    EXISTS (SELECT 1 FROM public.events)
  );
  PERFORM pg_catalog.setval(
    pg_catalog.pg_get_serial_sequence('public.attendance', 'id')::regclass,
    COALESCE((SELECT MAX(id) FROM public.attendance), 1),
    EXISTS (SELECT 1 FROM public.attendance)
  );
  PERFORM pg_catalog.setval(
    pg_catalog.pg_get_serial_sequence('public.users', 'id')::regclass,
    COALESCE((SELECT MAX(id) FROM public.users), 1),
    EXISTS (SELECT 1 FROM public.users)
  );
END;
$$;

REVOKE ALL ON FUNCTION public.advance_id_sequences() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.advance_id_sequences() TO service_role;
